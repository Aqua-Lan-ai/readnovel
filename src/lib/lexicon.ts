const byLenDesc = (a: string, b: string) => b.length - a.length
export const alt = (words: string[]) => [...words].sort(byLenDesc).join('|')

const END = String.raw`(?=[，,：:。！!？?…\s「『“"]|$)`
const FILL = String.raw`(?:著|着|了|一聲|一声|起來|起来)?`
const verbRe = (words: string[]) => new RegExp(`(?:${alt(words)})${FILL}${END}`)

export const SPEECH_RE = verbRe(SPEECH_VERBS)
export const SHOUT_RE = verbRe(SHOUT_VERBS)
